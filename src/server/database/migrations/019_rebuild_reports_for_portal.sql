CREATE TABLE IF NOT EXISTS reports (
  id TEXT PRIMARY KEY,
  project_id TEXT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  source TEXT DEFAULT 'widget' NOT NULL CHECK(source IN ('widget', 'manual', 'portal')),
  title TEXT NOT NULL,
  description TEXT,
  status TEXT DEFAULT 'open' NOT NULL CHECK(status IN ('open', 'in_progress', 'resolved', 'closed')),
  priority TEXT DEFAULT 'medium' NOT NULL CHECK(priority IN ('lowest', 'low', 'medium', 'high', 'highest')),
  annotations JSON,
  metadata JSON NOT NULL,
  reporter_email TEXT,
  reporter_name TEXT,
  assigned_to TEXT REFERENCES users(id) ON DELETE SET NULL,
  custom_fields JSON DEFAULT '{}',
  created_at TEXT DEFAULT (datetime('now')) NOT NULL,
  updated_at TEXT DEFAULT (datetime('now')) NOT NULL,
  resolved_at TEXT,
  resolved_by TEXT REFERENCES users(id) ON DELETE SET NULL,
  closed_at TEXT,
  forwarded_to JSON DEFAULT '[]',
  github_sync_status TEXT NULL CHECK(github_sync_status IN ('pending', 'synced', 'error')),
  github_sync_error TEXT NULL,
  github_issue_number INTEGER NULL,
  github_issue_url TEXT NULL,
  github_synced_at TEXT NULL,
  reporter_locale TEXT NOT NULL DEFAULT 'en',
  submission_id TEXT,
  board_position REAL NOT NULL DEFAULT 0,
  reporter_id TEXT REFERENCES reporters(id) ON DELETE SET NULL,
  claimable_email TEXT,
  original_description TEXT,
  original_description_backfilled INTEGER NOT NULL DEFAULT 0 CHECK(original_description_backfilled IN (0, 1)),
  owner_seen_at TEXT,
  last_reporter_activity_at TEXT,
  reporter_activity_seen_at TEXT
);
